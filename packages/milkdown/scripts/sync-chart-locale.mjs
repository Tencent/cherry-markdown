import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import locale from '../../cherry-markdown/src/locales/zh_CN.js';

// The published 0.11.10 Engine does not export its locale data. Generate only
// the messages used by the addon from Cherry's own source; never hand-maintain
// another translation table. No Cherry editor or toolbar runtime is imported.
const addon = readFileSync(
  new URL('../../cherry-markdown/src/addons/advance/cherry-table-echarts-plugin.js', import.meta.url),
  'utf8',
);
const keys = [...new Set([...addon.matchAll(/cherry\.locale\.(\w+)/g)].map((match) => match[1]))].sort();
const entries = keys.map((key) => {
  if (typeof locale[key] !== 'string') throw new Error(`Missing Cherry chart message: ${key}`);
  return `  ${key}: ${JSON.stringify(locale[key])},`;
});
const target = fileURLToPath(new URL('../src/cherry-chart-locale.ts', import.meta.url));
const generated = await format(
  `// Generated by scripts/sync-chart-locale.mjs from Cherry's chart messages.\nexport const cherryChartLocale = {\n${entries.join('\n')}\n} as const;\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 110 },
);
const changed = !existsSync(target) || readFileSync(target, 'utf8') !== generated;
if (process.argv.includes('--check')) {
  if (changed) throw new Error('Run sync-chart-locale.mjs to update Cherry chart messages.');
} else if (changed) writeFileSync(target, generated);
