import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
// Keep the list in Vite's config dependency graph so edits trigger regeneration.
import languages from './prism-languages.json' with { type: 'json' };

const require = createRequire(import.meta.url);
const components = require('prismjs/components.json');
const getLoader = require('prismjs/dependencies.js');
const outputFile = new URL('../src/utils/prism.js', import.meta.url);

// Resolve aliases and required/optional/modify dependencies exactly as the former
// babel-plugin-prismjs configuration did, without running a Babel transform.
export function generatePrismLanguages({ check = false } = {}) {
  const ids = getLoader(components, languages).getIds();
  const source = [
    '// Generated by build/generate-prism.js. Edit build/prism-languages.json instead.',
    "import Prism from './prism-runtime.js';",
    ...ids.map((id) => `import 'prismjs/components/prism-${id}.js';`),
    '',
    'export default Prism;',
    '',
  ].join('\n');
  let current;
  try {
    current = readFileSync(outputFile, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== source) {
    if (check) throw new Error('Prism language imports are stale. Run prism:generate in packages/cherry-markdown.');
    writeFileSync(outputFile, source);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generatePrismLanguages({ check: process.argv.includes('--check') });
}
